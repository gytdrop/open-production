import { chromium } from 'playwright';
import { writeFile, mkdir } from 'fs/promises';
const SHOTS = '.tmp/browser-test/screenshots';
await mkdir(SHOTS, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await context.newPage();
const consoleMsgs = [];
const networkErrors = [];
page.on('console', (m) => consoleMsgs.push({ type: m.type(), text: m.text() }));
page.on('pageerror', (e) => consoleMsgs.push({ type: 'pageerror', text: e.message }));
page.on('requestfailed', (r) => networkErrors.push({ url: r.url(), failure: r.failure() ? r.failure().errorText : null }));
page.on('response', (r) => { if (r.status() >= 400) networkErrors.push({ url: r.url(), status: r.status() }); });
async function shot(name) { await page.screenshot({ path: SHOTS + '/' + name + '.png', fullPage: false }); }
async function dump(label) { await writeFile('.tmp/browser-test/console.json', JSON.stringify({label, msgs: consoleMsgs}, null, 2)); await writeFile('.tmp/browser-test/network.json', JSON.stringify({label, errs: networkErrors}, null, 2)); }
console.log('STEP: open flow');
await page.goto('http://127.0.0.1:5173/flow', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(2500);
await shot('flow-1-stage1');
console.log('STEP: type topic');
await page.locator('textarea').first().fill('A short film about a barista who discovers their regular customer is an AI testing whether humans can tell.');
await page.waitForTimeout(400);
console.log('STEP: click continue');
await page.getByRole('button', { name: /Continue/ }).click();
await page.waitForTimeout(3500);
await shot('flow-3-angles');
const articleCount = await page.locator('article').count();
console.log('articles on stage3:', articleCount);
const steps = await page.locator('[role=button][aria-label^=\"Step\"]').count();
console.log('steps:', steps);
for (const i of [1, 2, 3, 4, 5, 6]) {
  if (steps > i) await page.locator('[role=button][aria-label^=\"Step\"]').nth(i).click();
  await page.waitForTimeout(700);
  await shot('flow-stage-' + (i + 1));
}
console.log('STEP: open console');
await page.goto('http://127.0.0.1:5173/console', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(2500);
await shot('console-empty');
console.log('STEP: open console with id');
await page.goto('http://127.0.0.1:5173/console?id=local-test', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(3500);
await shot('console-with-id');
await dump('desktop');
await context.close();
const mobileCtx = await browser.newContext({ viewport: { width: 390, height: 800 } });
const mp = await mobileCtx.newPage();
mp.on('console', (m) => consoleMsgs.push({ type: 'mobile-' + m.type(), text: m.text() }));
mp.on('pageerror', (e) => consoleMsgs.push({ type: 'mobile-pageerror', text: e.message }));
await mp.goto('http://127.0.0.1:5173/flow', { waitUntil: 'domcontentloaded' });
await mp.waitForTimeout(2000);
await mp.screenshot({ path: SHOTS + '/mobile-flow.png', fullPage: false });
await mp.locator('textarea').first().fill('A short film about a barista who discovers their regular customer is an AI testing whether humans can tell.');
await mp.getByRole('button', { name: /Continue/ }).click();
await mp.waitForTimeout(3500);
await mp.screenshot({ path: SHOTS + '/mobile-angles.png', fullPage: false });
await dump('full');
await browser.close();
console.log('DONE');
